/* PROMO CAROUSEL */

const promoWrap = document.querySelector(".promo-wrap");
const promoTrack = document.getElementById("promoTrack");
const promoSlides = document.querySelectorAll(".promo-slide");
const promoDots = document.querySelectorAll(".promo-dot");

let currentSlide = 0;
let carouselTimer;

let startX = 0;
let startY = 0;
let isPointerDown = false;
let bannerWasSwiped = false;

function showSlide(index) {
  currentSlide = index;

  promoTrack.style.transform =
    `translateX(-${index * 100}%)`;

  promoDots.forEach((dot, i) => {
    dot.classList.toggle("active", i === index);
  });
}

function startCarousel() {
  clearInterval(carouselTimer);

  if (promoSlides.length <= 1) return;

  carouselTimer = setInterval(() => {
    const next = (currentSlide + 1) % promoSlides.length;
    showSlide(next);
  }, 5000);
}

/* KLIK TITIK NAVIGASI */

promoDots.forEach((dot, index) => {
  dot.addEventListener("click", () => {
    showSlide(index);
    startCarousel();
  });
});

/* GESER MANUAL */

promoWrap.addEventListener("pointerdown", (event) => {
  if (event.target.closest(".promo-dot")) return;

  if (event.pointerType === "mouse" && event.button !== 0) return;

  startX = event.clientX;
  startY = event.clientY;
  isPointerDown = true;
});

promoWrap.addEventListener("pointerup", (event) => {
  if (!isPointerDown) return;

  isPointerDown = false;

  const distanceX = event.clientX - startX;
  const distanceY = event.clientY - startY;

  // Pastikan gerakan lebih dominan ke kiri/kanan
  if (
    Math.abs(distanceX) > 45 &&
    Math.abs(distanceX) > Math.abs(distanceY)
  ) {
    let nextSlide;

    if (distanceX < 0) {
      // Geser ke kiri: banner berikutnya
      nextSlide = (currentSlide + 1) % promoSlides.length;
    } else {
      // Geser ke kanan: banner sebelumnya
      nextSlide =
        (currentSlide - 1 + promoSlides.length) % promoSlides.length;
    }

    showSlide(nextSlide);
    startCarousel();

    bannerWasSwiped = true;

    setTimeout(() => {
      bannerWasSwiped = false;
    }, 400);
  }
});

promoWrap.addEventListener("pointercancel", () => {
  isPointerDown = false;
});

/* Cegah banner terbuka saat selesai digeser */

promoWrap.addEventListener("click", (event) => {
  if (bannerWasSwiped) {
    event.preventDefault();
    event.stopPropagation();
    bannerWasSwiped = false;
  }
}, true);

